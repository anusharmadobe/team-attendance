# ── IST → unix timestamp ──────────────────────────────────────────────────────
# IST = UTC+5:30 (+19800 s).  timegm treats naive datetime as UTC, so subtract.
def ts(ist_str: str) -> str:
    dt = datetime.strptime(ist_str, "%Y-%m-%d %H:%M:%S")
    return str(calendar.timegm(dt.timetuple()) - 19800)


